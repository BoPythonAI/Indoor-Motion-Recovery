"""Render English demos from recorded RGB frames and audited physics anchors.

Usage: python tools/render_demos.py --inputs /path/to/demo_sources/inputs.json
No motion, contact, or post-termination physics is generated by this script.
"""
from __future__ import annotations
import argparse
import hashlib
import json
import math
import subprocess
from pathlib import Path

import imageio_ffmpeg
import numpy as np
from PIL import Image, ImageDraw, ImageFont

FPS = 30
W, H = 960, 720
HEADER, FOOTER = 64, 86
PANEL_H = HEADER + H + FOOTER
BG = (245, 249, 251)
INK = (23, 44, 57)
MUTED = (91, 109, 119)
TEAL = (16, 139, 143)
RED = (225, 65, 83)
ORANGE = (242, 143, 59)
WHITE = (255, 255, 255)
LABELS = {
    "mesh": ("Original Motion", "Mesh"),
    "baseline": ("Baseline Controller", "Capsule Physics"),
    "h1": ("H1 Model", "Capsule Physics"),
}


def font_path():
    candidates = [
        Path("C:/Windows/Fonts/arial.ttf"),
        Path("/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf"),
        Path("/Library/Fonts/Arial.ttf"),
    ]
    return next(p for p in candidates if p.exists())


FONT = {}


def font(size):
    if size not in FONT:
        FONT[size] = ImageFont.truetype(str(font_path()), size)
    return FONT[size]


def sha(p):
    return hashlib.sha256(Path(p).read_bytes()).hexdigest()


def frames(path):
    stream = imageio_ffmpeg.read_frames(str(path), pix_fmt="rgb24")
    meta = next(stream)
    assert abs(meta["fps"] - FPS) < .01, meta
    width, height = meta["size"]
    result = [Image.frombytes("RGB", (width, height), b).resize((W, H), Image.Resampling.LANCZOS)
              for b in stream]
    assert result
    return result


def capsule_marker(draw, point, color, label, side="left"):
    x, y = point
    # Omit an off-screen point instead of inventing an in-frame object location.
    if not (12 < x < W-12 and 14 < y < H-14):
        return
    draw.ellipse((x-16, y-16, x+16, y+16), outline=WHITE, width=7)
    draw.ellipse((x-16, y-16, x+16, y+16), outline=color, width=4)
    tw = draw.textbbox((0, 0), label, font=font(20))[2]
    bx = 16 if side == "left" else W-tw-36
    by = 17
    draw.rounded_rectangle((bx, by, bx+tw+20, by+37), 7, fill=INK)
    draw.text((bx+10, by+6), label, font=font(20), fill=color)
    draw.line([(bx+tw/2+10, by+37), (x, y-18)], fill=color, width=2)


def push_arrow(draw, tail, tip):
    a, b = np.asarray(tail, float), np.asarray(tip, float)
    v = b-a
    if np.linalg.norm(v) < 8:
        return
    v /= np.linalg.norm(v)
    n = np.array([-v[1], v[0]])
    draw.line([tuple(a), tuple(b-v*12)], fill=WHITE, width=15)
    draw.line([tuple(a), tuple(b-v*12)], fill=ORANGE, width=9)
    draw.polygon([tuple(b), tuple(b-v*29+n*16), tuple(b-v*29-n*16)],
                 fill=ORANGE, outline=WHITE)
    draw.ellipse((a[0]-18, a[1]-18, a[0]+18, a[1]+18),
                 fill=ORANGE, outline=WHITE, width=2)
    draw.polygon([(a[0]+2,a[1]-13),(a[0]-9,a[1]+1),(a[0]-1,a[1]+1),
                  (a[0]-4,a[1]+13),(a[0]+10,a[1]-3),(a[0]+2,a[1]-3)], fill=WHITE)


def warning(draw, point, label):
    x, y = point
    draw.ellipse((x-27,y-27,x+27,y+27), outline=INK, width=9)
    draw.ellipse((x-27,y-27,x+27,y+27), outline=RED, width=5)
    tx, ty = max(36,min(W-280,x+55)), max(85,min(H-60,y-55))
    draw.line([(x+18,y-18),(tx,ty+20)], fill=RED, width=4)
    draw.polygon([(tx,ty-23),(tx-25,ty+21),(tx+25,ty+21)],fill=RED,outline=WHITE)
    draw.line([(tx,ty-9),(tx,ty+5)], fill=WHITE,width=4)
    draw.ellipse((tx-2,ty+11,tx+2,ty+15),fill=WHITE)
    tw=draw.textbbox((0,0),label,font=font(20))[2]
    draw.rounded_rectangle((tx+31,ty-20,tx+51+tw,ty+20),6,fill=INK)
    draw.text((tx+41,ty-12),label,font=font(20),fill=WHITE)


def panel(source, scene, mode, idx, held, intro):
    im=source.copy()
    d=ImageDraw.Draw(im)
    color=TEAL
    if mode=="mesh":
        status="Reference motion"
        detail=f"Reference time {(idx+1)/FPS:.2f} s"
    else:
        row=scene["annotations"][mode][idx]
        capsule_marker(d,row["goal_px"],TEAL,scene["goal_label"],"left")
        capsule_marker(d,row["forbidden_px"],RED,scene["forbidden_label"],"right")
        if row["push_active"] and not intro and not held:
            push_arrow(d,row["push_tail_px"],row["push_tip_px"])
            status=f"PUSH  |  0.75 BW  |  {row['force_N']:.1f} N"
            color=ORANGE
        else:
            status="Walking / recovering balance" if mode=="h1" else "Walking toward the goal"
        terminal=idx==len(scene["annotations"][mode])-1
        if terminal:
            if mode=="baseline":
                warning(d,row["failure_px"],scene["failure_marker"])
                status=scene["failure_status"]
                color=RED
            else:
                status="SUCCESS  |  Goal reached, stable, no forbidden contact"
        detail=f"Simulation {(idx+1)/FPS:.2f} s  |  Forbidden contact {row['forbidden_force_N']:.1f} N"
    if intro:
        detail += "  |  Start hold"
    elif held:
        detail += "  |  Recording ended - held frame"
    else:
        detail += "  |  0.5x playback"
    out=Image.new("RGB",(W,PANEL_H),BG)
    out.paste(im,(0,HEADER))
    d=ImageDraw.Draw(out)
    d.text((22,16),LABELS[mode][0],font=font(30),fill=INK)
    sub=LABELS[mode][1]
    tw=d.textbbox((0,0),sub,font=font(21))[2]
    d.text((W-tw-22,22),sub,font=font(21),fill=MUTED)
    d.rectangle((0,HEADER+H,W,HEADER+H+4),fill=color)
    d.text((22,HEADER+H+13),status,font=font(25),fill=color)
    d.text((22,HEADER+H+50),detail,font=font(20),fill=MUTED)
    return out


def encoder(path, size):
    return subprocess.Popen([
        imageio_ffmpeg.get_ffmpeg_exe(),"-y","-loglevel","error",
        "-f","rawvideo","-pix_fmt","rgb24","-s",f"{size[0]}x{size[1]}",
        "-r",str(FPS),"-i","-","-an","-c:v","libx264","-preset","fast",
        "-crf","20","-pix_fmt","yuv420p","-movflags","+faststart",str(path)
    ],stdin=subprocess.PIPE)


def render_scene(scene, source_root, out):
    key=scene["id"]
    clips={k:frames(source_root/scene["videos"][k]) for k in LABELS}
    for mode in ["baseline","h1"]:
        assert len(clips[mode])==len(scene["annotations"][mode])
        assert sum(r["push_active"] for r in scene["annotations"][mode])==6
    longest=max(map(len,clips.values()))
    count=15+2*longest+45
    dest=out/key
    dest.mkdir(parents=True,exist_ok=True)
    writers={k:encoder(dest/f"{k}.mp4",(W,PANEL_H)) for k in LABELS}
    combined_size=(1728,642)
    combined=encoder(dest/"comparison.mp4",combined_size)
    mappings={k:[] for k in LABELS}
    gifs=[]
    cache={}
    for oi in range(count):
        raw_index=max(0,(oi-15)//2)
        displayed=[]
        for mode in LABELS:
            idx=min(raw_index,len(clips[mode])-1)
            intro=oi<15
            held=not intro and raw_index>=len(clips[mode])
            mappings[mode].append(idx)
            cache_key=(mode,idx,held,intro)
            if cache_key not in cache:
                im=panel(clips[mode][idx],scene,mode,idx,held,intro)
                cache[cache_key]=(im.tobytes(),im.resize((576,522),Image.Resampling.LANCZOS))
            b,small=cache[cache_key]
            writers[mode].stdin.write(b)
            displayed.append(small)
        comp=Image.new("RGB",combined_size,BG)
        d=ImageDraw.Draw(comp)
        d.text((25,13),scene["title"],font=font(31),fill=INK)
        d.text((25,55),"Task: "+scene["task"],font=font(24),fill=INK)
        d.text((25,86),"Avoid: "+scene["avoid"]+"   |   Push: 0.75 BW for 0.20 s",font=font(21),fill=MUTED)
        for j,img in enumerate(displayed):
            comp.paste(img,(j*576,120))
        combined.stdin.write(comp.tobytes())
        if oi%6==0:
            gifs.append(comp.resize((864,321),Image.Resampling.LANCZOS))
        if oi==count-1:
            comp.save(dest/"poster.jpg",quality=95)
        if any(scene["annotations"][m][min(raw_index,len(scene["annotations"][m])-1)]["push_active"]
               for m in ["baseline","h1"]) and oi==15+2*scene["push_preview_index"]:
            comp.save(dest/"push.jpg",quality=95)
    for proc in list(writers.values())+[combined]:
        proc.stdin.close()
        assert proc.wait()==0
    gifs[0].save(dest/"preview.gif",save_all=True,append_images=gifs[1:],duration=200,
                 loop=0,optimize=True)
    for mode in LABELS:
        assert set(mappings[mode])==set(range(len(clips[mode])))
    audit={"scene":key,"source_fps":FPS,"playback_speed":.5,"output_frames":count,
           "duration_s":count/FPS,"source_frames":{k:len(v) for k,v in clips.items()},
           "all_source_frames_covered":True,"frame_mapping":mappings,
           "terminal_hold":"Existing final frame only; no post-termination physics.",
           "source_sha256":{k:sha(source_root/scene["videos"][k]) for k in LABELS},
           "output_sha256":{p.name:sha(p) for p in dest.iterdir() if p.suffix==".mp4"}}
    (dest/"audit.json").write_text(json.dumps(audit,indent=2)+"\n",encoding="utf-8")
    print(json.dumps({k:audit[k] for k in ["scene","duration_s","source_frames","all_source_frames_covered"]}),flush=True)


def main():
    p=argparse.ArgumentParser()
    p.add_argument("--inputs",type=Path,required=True)
    p.add_argument("--output",type=Path,default=Path(__file__).resolve().parents[1]/"docs/media")
    args=p.parse_args()
    data=json.loads(args.inputs.read_text(encoding="utf-8"))
    for scene in data["scenes"]:
        render_scene(scene,args.inputs.parent,args.output)


if __name__=="__main__":
    main()
